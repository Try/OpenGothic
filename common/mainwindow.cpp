void MainWindow::drawGamepadHints(Painter& p) {
  using Context = GamepadInput::Context;
  const auto context = gamepadContext().context;
  if(rootMenu.hasModalInput() || inventory.hasGamepadModal())
    return;
  const auto& settings = gamepad.settings();
  std::string text;
  if(context==Context::Menu) {
    text = "Square / F1: Controller settings";
    if(gamepad.device()!=0 && settings.hints)
      text += "   Cross: Confirm   Circle / Options: Back";
    }
  else if(gamepad.device()!=0 && settings.hints) {
    switch(context) {
      case Context::Gameplay: {
        const auto add = [&](KeyCodec::Action action) {
          std::string buttons;
          for(auto button : GamepadSettings::remappableButtons) {
            if(settings.bindings[size_t(button)]!=action)
              continue;
            if(!buttons.empty())
              buttons += '/';
            buttons += GamepadSettings::buttonName(button);
            }
          if(buttons.empty())
            return;
          if(!text.empty())
            text += "   ";
          text += buttons+": ";
          text += GamepadSettings::actionName(action);
          };
        add(KeyCodec::ActionGeneric);
        add(KeyCodec::Jump);
        add(KeyCodec::Weapon);
        add(KeyCodec::Inventory);
        add(KeyCodec::Log);
        text += "\nLeft stick: Move   Right stick: Camera   Options: Menu";
        break;
        }
      case Context::Inventory:
        text = "Cross: Use / Transfer 1   Square: Quantity / Drop   Triangle: Spell slot\nL1 / R1: Panel   Circle / Options: Back";
        break;
      case Context::Dialog:
        text = "Up / Down: Reply   Cross: Confirm   Circle / Options: Skip phrase";
        break;
      case Context::Document:
        text = "Circle / Options: Close document";
        break;
      case Context::Chapter:
        text = "Circle / Options: Close chapter";
        break;
      default:
        break;
      }
    }
  const auto area = clientRect();
  if(text.empty() || area.w<=20 || area.h<=20)
    return;
  auto font = Resources::font(Gothic::interfaceScale(this));
  const int width = area.w-20;
  const int padding = std::min(8,width/4);
  const int textWidth = std::max(1,width-2*padding);
  const int maxHeight = std::max(1,area.h/4-2*padding);
  auto height = font.textSize(textWidth,text).h;
  if(height>maxHeight) {
    font.setScale(Gothic::interfaceScale(this)*float(maxHeight)/float(std::max(1,height)));
    height = font.textSize(textWidth,text).h;
    }
  p.pushState();
  const int x = area.x+10, y = area.y+10;
  p.setScissor(x,y,width,height+2*padding);
  p.setBrush(Color(0.04f,0.04f,0.04f,0.9f));
  p.drawRect(x,y,width,height+2*padding);
  font.drawText(p,x+padding,y+padding+font.pixelSize(),textWidth,
                std::max(1,height),text,NoAlign);
  p.popState();
  }

void MainWindow::render(){
  try {
    static uint64_t time=Application::tickCount();

    static bool once=true;
    if(once) {
      Gothic::inst().emitGlobalSoundWav("GAMESTART.WAV");
      once=false;
      }

    if(T_UNLIKELY(Gothic::inst().isBenchmarkModeCi())) {
      const auto st = Gothic::inst().checkLoading();
      if(st==Gothic::LoadState::Loading) {
        // skip loading frames in benchmark-ci mode, for sake of easier tooling
        return;
        }
      }

    /*
      Note: game update goes first
      once player position is updated, animation bones(cameraBone in particular) can be updated
      lastly - camera position
      */
    const uint64_t dt = tick();
    updateAnimation(dt);
    tickCamera(dt);

    auto& sync = fence[cmdId];
    if(!sync.wait(0)) {
      // GPU rendering is not done, pass to next frame
      std::this_thread::yield();
      return;
      }
    Resources::resetRecycled(cmdId);

    if(video.isActive()) {
      video.paint(device,cmdId);
      uiLayer.clear();
      PaintEvent p(uiLayer,atlas,this->w(),this->h());
      video.paintEvent(p);
      }
    else if(needToUpdate() || Gothic::inst().checkLoading()!=Gothic::LoadState::Idle) {
      dispatchPaintEvent(uiLayer,atlas);

      PaintEvent hints(uiLayer,atlas,this->w(),this->h());
      Painter hintPainter(hints);
      drawGamepadHints(hintPainter);

      numOverlay.clear();
      PaintEvent p(numOverlay,atlas,this->w(),this->h());
      inventory.paintNumOverlay(p);
      }
    uiMesh [cmdId].update(device,uiLayer);
    numMesh[cmdId].update(device,numOverlay);

    CommandBuffer& cmd = commands[cmdId];
    {
    auto enc = cmd.startEncoding(device);
    renderer.draw(swapchain[swapchain.currentImage()],enc,cmdId,uiMesh[cmdId],numMesh[cmdId],inventory,video);
    }
    sync = device.submit(cmd);
    device.present(swapchain);
    cmdId = (cmdId+1u)%Resources::MaxFramesInFlight;

    auto t = Application::tickCount();
    auto frameTime = maxFpsInv;
    if(!Gothic::inst().isInGame() && !video.isActive())
      frameTime = std::max<uint64_t>(frameTime,16);
    if(t-time<frameTime) {
      uint32_t delay = uint32_t(frameTime-(t-time));
      Application::sleep(delay);
      t += delay;
      }
    fps.push(t-time);
    if(Gothic::inst().isBenchmarkMode() && Gothic::inst().world()!=nullptr && Gothic::inst().world()->currentCs()!=nullptr)
      benchmark.push(t-time);
    time = t;
    }
  catch(const Tempest::SwapchainSuboptimal&) {
    Log::e("swapchain is outdated - reset renderer");
    device.waitIdle();
    swapchain.reset();
    }
  }

double MainWindow::Fps::get() const {
  uint64_t sum=0,num=0;
  for(auto& i:dt)
    if(i>0) {
      sum+=i;
      num++;
      }
  if(num==0 || sum==0)
    return 60;
  uint64_t fps = (1000*100*num)/sum;
  return double(fps)/100.0;
  }

void MainWindow::Fps::push(uint64_t t) {
  for(size_t i=9;i>0;--i)
    dt[i]=dt[i-1];
  dt[0]=t;
  }

void MainWindow::BenchmarkData::push(uint64_t t) {
  fpsSum += t>0 ? (1000.0/double((t))) : 60.0;
  numFrames++;
  auto at = std::lower_bound(low1procent.begin(), low1procent.end(), t, std::greater<uint64_t>());
  low1procent.insert(at, t);
  low1procent.resize(std::min(low1procent.size(), (numFrames+99)/100));
  }

void MainWindow::BenchmarkData::clear() {
  low1procent.reserve(128);
  low1procent.clear();
  numFrames = 0;
  fpsSum = 0;
  }
